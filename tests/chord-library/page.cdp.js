// Chord Library catalogue in headless Chrome. Run: node tests/chord-library/page.cdp.js  (serves the repo itself on 8510)
const http = require("http"), fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../.."), { launch } = require(ROOT + "/tests/band/lead/cdp.js");
const srv = http.createServer((q, s) => { const f = path.join(ROOT, decodeURIComponent(q.url.split(/[?#]/)[0]));
  fs.readFile(f, (e, d) => { if (e) { s.writeHead(404); s.end(); return; } s.writeHead(200, { "content-type": f.endsWith(".js") ? "text/javascript" : "text/html" }); s.end(d); }); }).listen(8510);
(async () => {
  const b = await launch(), out = process.argv[2] || "/tmp";
  let fails = 0; const check = (name, ok, info) => { console.log((ok ? "ok   " : "FAIL ") + name + (info ? "  " + info : "")); if (!ok) fails++; };
  await b.goto("http://127.0.0.1:8510/apps/chord-library/index.html"); await b.sleep(400);
  const count = () => b.eval("document.getElementById('count').textContent");
  const search = async q => { await b.eval(`document.getElementById('q').value=${JSON.stringify(q)}; document.getElementById('search-form').requestSubmit()`); await b.sleep(500); };
  check("default Cmaj7 loads", /voicing/.test(await count()), await count());
  await search("Cmaj7 drop3 bass:6");
  check("Cmaj7 drop3 bass on 6", +(await count()).replace(/\D/g, "") > 0, await count());
  const allBass6 = await b.eval("[...document.querySelectorAll('.card')].every(c=>/Bass on 6/.test(c.textContent)&&/Drop 3/.test(c.textContent))");
  check("every card is drop 3 with bass on 6", allBass6);
  await b.shot(out + "/chordlib-drop3.png", false);
  await search("Bbm7b5 root:5 noskip");
  check("Bbm7b5 root on 5 spelled with flats", await b.eval("document.querySelector('.card .name').textContent.startsWith('B♭m7♭5')"), await b.eval("document.querySelector('.card .name')&&document.querySelector('.card .name').textContent"));
  await search("G7 drop2 set:4321 top:3");
  check("G7 drop2 4-3-2-1 3rd on top", /voicing/.test(await count()) && !/No/.test(await count()), await count());
  await search("dominant drop2 any noopen");
  check("all dominant drop2 in every key", /voicing/.test(await count()), await count());
  await search("C caged:full");
  const shapes = await b.eval("[...document.querySelectorAll('.card .name')].map(n=>n.textContent)");
  check("C major: the five whole CAGED shapes", ["x32010","x35553","875558","8-10-10-9-8-8","x-x-10-12-13-12"].every(f => shapes.some(n => n.endsWith(f))), shapes.join(", "));
  await search("C");
  check("most common first: a whole CAGED shape leads", await b.eval("/C\\/A\\/G\\/E\\/D shape|[CAGED] shape/.test(document.querySelector('.card').textContent) && !/part of/.test(document.querySelector('.card').textContent)"), await b.eval("document.querySelector('.card').textContent"));
  await search("A7 Eshape");
  check("A7 E shape found", /voicing/.test(await count()) && !/No/.test(await count()), await count());
  await search("piano Cm9");
  check("keyboard", /voicing/.test(await count()), await count());
  await b.eval("document.querySelector('.card').click()"); await b.sleep(200);
  check("detail dialog opens", await b.eval("document.getElementById('dlg').open"));
  await b.shot(out + "/chordlib-keys.png", false);
  await b.eval("document.getElementById('dlg').close(); const n=document.getElementById('f-notation'); n.value='on'; n.dispatchEvent(new Event('change'))"); await b.sleep(600);
  check("notation on piano cards", await b.eval("document.querySelectorAll('.card .notation svg').length>0"));
  await b.shot(out + "/chordlib-notation.png", false);
  await b.eval("const t=document.getElementById('f-tags'); t.value='hide'; t.dispatchEvent(new Event('change'))");
  check("tags hidden", await b.eval("getComputedStyle(document.querySelector('.card .tags')).display==='none'"));
  await search("guitar Cmaj7 drop2");
  check("notation on guitar cards", await b.eval("document.querySelectorAll('.card .notation svg').length>0"));
  await b.shot(out + "/chordlib-guitar-notation.png", false);
  await b.resize(390, 800); await b.sleep(200);
  check("no horizontal scroll on phone", await b.eval("document.documentElement.scrollWidth<=390"));
  check("no page errors", !b.errors.length, b.errors.join(" | "));
  await b.close(); srv.close(); process.exit(fails ? 1 : 0);
})();
