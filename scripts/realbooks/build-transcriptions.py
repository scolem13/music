#!/usr/bin/env python3
"""python3 -I scripts/realbooks/build-transcriptions.py [DIR]
Reads the rhythm/chord/lyric ABC transcriptions (default ~/Downloads/realpop2-rhythm), formats them
with abcfmt, and writes apps/realbooks/rhythm-transcriptions.js (window.RHYTHM_TRANSCRIPTIONS).
Pitches are NOT transcribed (every note is B). Status: ok = every bar a full measure; check = some bars fail;
partial = %partial/'not transcribed'/'not done' noted."""
import sys, os, re, json, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from abcfmt import format_abc
d = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Downloads/realpop2-rhythm')
out = []
for f in sorted(glob.glob(os.path.join(d, '*.abc')), key=lambda p: int(re.match(r'(\d+)', os.path.basename(p)).group(1))):
    raw = open(f).read()
    text, s = format_abc(raw)
    unsure = len(re.findall(r'^%unsure', text, re.M))
    note = (re.search(r'^%note (.*)', raw, re.M) or [0, ''])[1].replace('Pitches NOT transcribed: every note is written as B.', '').replace('Pitches NOT transcribed: every note is B.', '').strip()
    title = (re.search(r'^T:(.*)', raw, re.M) or [0, os.path.basename(f)])[1].strip()
    page = (re.search(r'pdf (\d+)', raw) or [0, ''])[1]
    out.append(dict(id=os.path.basename(f)[:-4], title=title, pdf=page, bad=s['bad'], unsure=unsure,
                    note=note, abc=text))
body = json.dumps(out, indent=0, ensure_ascii=False)
open(os.path.join(os.path.dirname(__file__), '../../apps/realbooks/rhythm-transcriptions.js'), 'w').write(
    '// generated by scripts/realbooks/build-transcriptions.py\nwindow.RHYTHM_TRANSCRIPTIONS = ' + body + ';\n')
print(len(out), 'tunes')
