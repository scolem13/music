#!/usr/bin/env python3
"""python3 -I scripts/realbooks/build-transcriptions.py [DIR ...]
Reads the rhythm/chord/lyric ABC transcriptions, formats them with abcfmt, and writes
apps/realbooks/rhythm-transcriptions.js (window.RHYTHM_TRANSCRIPTIONS). Pitches are NOT transcribed (every note is B).

Default sources: ~/Downloads/realpop2-rhythm (The Real Pop Book Vol. 2) and every book folder in
~/Downloads/realBooks/sher-rhythm. A DIR given on the command line is read as one book named after the folder.

Each tune carries: book, bad (count of bars that aren't a full measure), off (their bar numbers), first (0 when the tune
starts with a pickup, else 1) and flags [{bars, groups, text}] from the %unsure lines (see abcbars.py for the
[bars ...] tag and how bars are counted; groups are 0-based bar indexes in the order written, for the page)."""
import sys, os, re, json, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from abcfmt import format_abc
import abcbars

HOME = os.path.expanduser('~')
BOOKS = {'realpop2-rhythm': 'The Real Pop Book Vol. 2', 'real-easy-book-c': 'The Real Easy Book (C)',
         'The_Colorado_Cookbook': 'The Colorado Cookbook', 'New_Real_Book_Volume2': 'The New Real Book Vol. 2'}


def sources():
    if len(sys.argv) > 1: return [(d, BOOKS.get(os.path.basename(d.rstrip('/')), os.path.basename(d.rstrip('/')).replace('_', ' '))) for d in sys.argv[1:]]
    out = [(os.path.join(HOME, 'Downloads/realpop2-rhythm'), BOOKS['realpop2-rhythm'])]
    for d in sorted(glob.glob(os.path.join(HOME, 'Downloads/realBooks/sher-rhythm/*/'))):
        b = os.path.basename(d.rstrip('/')); out.append((d, BOOKS.get(b, b.replace('_', ' '))))
    return out


out = []
for d, book in sources():
    pre = '' if os.path.basename(d.rstrip('/')) == 'realpop2-rhythm' else os.path.basename(d.rstrip('/')) + '/'   # old ids kept: comments use them
    files = glob.glob(os.path.join(d, '*.abc'))
    for f in sorted(files, key=lambda p: (int((re.match(r'(\d+)', os.path.basename(p)) or [0, 0])[1]), p)):
        raw = open(f).read()
        text, s = format_abc(raw)
        bs, first = abcbars.bars(raw)
        note = (re.search(r'^%note (.*)', raw, re.M) or [0, ''])[1]
        note = re.sub(r'Pitches NOT transcribed: every note is (written as )?B\.', '', note).strip()
        title = (re.search(r'^T:(.*)', raw, re.M) or [0, os.path.basename(f)])[1].strip()
        page = (re.search(r'pdf (\d+)', raw) or [0, ''])[1]
        form = (re.search(r'^%form (.*)', raw, re.M) or [0, ''])[1].strip()
        off = abcbars.off_bars(raw)
        flags = abcbars.flags(raw)
        out.append(dict(id=pre + os.path.basename(f)[:-4], book=book, title=title, pdf=page, form=form, bad=len(off), off=off,
                        first=first, unsure=len(flags), flags=flags, note=note, abc=text))
body = json.dumps(out, indent=0, ensure_ascii=False)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../apps/realbooks/rhythm-transcriptions.js'), 'w').write(
    '// generated by scripts/realbooks/build-transcriptions.py\nwindow.RHYTHM_TRANSCRIPTIONS = ' + body + ';\n')
print(len(out), 'tunes')
