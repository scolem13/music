// mtd-recordings.mjs: writes apps/themes/themes-recordings.js, the Musical Theme Dataset's recording of each Classical Theme
// as a Works recording (r2: "mtd/<theme id>.mp3"), loaded on Classical Themes between works-data.js and works.js.
// A theme already in a work gets the recording added to it; any other theme gets a small work of its own ("mtd-<id>").
// The clips are excerpts of commercial CDs (not under MTD's CC BY licence), so they live only in the private bucket.
//   node scripts/mtd-recordings.mjs [~/Downloads/MTD_1.0.0]
// MP3s: ffmpeg -i data_AUDIO/<MTD file>.wav -b:a 128k <theme id>.mp3, uploaded with
//   cf r2 buckets objects upload mtd/<id>.mp3 --bucket-name everything-music-mlt --file <id>.mp3 --content-type audio/mpeg
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const mtd = process.argv[2] || path.join(os.homedir(), "Downloads/MTD_1.0.0");
const metaDir = path.join(mtd, "MTD/data_META");

// theme ids on the page: the EDM number, with -1 / -2 where MTD has two recordings of one theme (MTD0739-1 -> 0745-1)
const themeIds = new Set(fs.readdirSync(path.join(root, "scripts/theme-sources/mtd")).map((f) => f.replace(/\.abc$/, "")));
const T = {};
{ const w = {}; new Function("window", fs.readFileSync(path.join(root, "apps/themes/themes-data.js"), "utf8"))(w);
  w.CLASSICAL_THEMES.forEach((t) => { T[t.id] = { title: t.title, composer: t.first + " " + t.last }; }); }
const recs = {}, names = {};
for (const f of fs.readdirSync(metaDir).filter((f) => f.endsWith(".json")).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(metaDir, f), "utf8"));
  const part = (/^MTD\d+(-\d)_/.exec(f) || [])[1] || "";
  // two recordings span two numbers ("0475+0476"): the page has the first; the file keeps the full name
  const file = m.EDMID + part, id = file.split("+")[0];
  if (!themeIds.has(id)) { console.warn("no theme for", f, id); continue; }
  const performer = String(m.PerformanceID || "").replace(/([a-z])([A-Z])/g, "$1 $2");
  names[id] = T[id] || { title: "", composer: "" };
  recs[id] = { r2: "mtd/" + file + ".mp3", performer, title: "Theme excerpt" + (performer ? " (" + performer + ")" : ""),
    note: "From the Musical Theme Dataset (" + m.StartTime + "–" + m.EndTime + " of the track); for class use only." };
}

const out = `// Generated by scripts/mtd-recordings.mjs (${Object.keys(recs).length} recordings). Do not edit.
// Adds the Musical Theme Dataset's recording of each theme to window.WORKS (load after works-data.js, before works.js).
(function (g) {
  var W = g.WORKS = g.WORKS || {}, R = ${JSON.stringify(recs)}, N = ${JSON.stringify(names)};
  var byTheme = {};
  Object.keys(W).forEach(function (wid) { ((W[wid].in || {}).theme || []).forEach(function (t) { byTheme[t] = wid; }); });
  Object.keys(R).forEach(function (id) {
    var wid = byTheme[id];
    if (wid) { (W[wid].recordings = W[wid].recordings || []).push(R[id]); return; }
    W["mtd-" + id] = { title: N[id].title, composer: N[id].composer, in: { theme: [id] }, recordings: [R[id]] };
  });
})(window);
`;
fs.writeFileSync(path.join(root, "apps/themes/themes-recordings.js"), out);
console.log("wrote apps/themes/themes-recordings.js:", Object.keys(recs).length, "recordings");
