// hutchinson-clips.mjs: every Hutchinson YouTube excerpt on the theory/ pages, with its start/stop times, written to
// research_notes/hutchinson-clips.org (one heading per page, one row per clip). Rerun after the pages change:
//   node scripts/works/hutchinson-clips.mjs
// Bars: filled in only when the page text near the clip names them ("mm. 1–8", "bars 5-12", "m. 3"); otherwise blank.
// Clip notation from apps/shared/data/hutchinson/index.json (scripts/works/hutchinson-abc.mjs) fills the Bars and Notation columns:
// "excerpt <file>", "chords <file>", "riff <file> (unverified)", or "source <id>" (whole piece on the site, clip's bars not known yet).
// ABC: "yes (<where>)" when the piece is already on the site as notation (tune collection, works-data tune/score/analysed).
import fs from "fs"; import path from "path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
global.window = {}; (0, eval)(fs.readFileSync(path.join(root, "apps/shared/works/works-data.js"), "utf8"));
const W = window.WORKS || window.WORKS_DATA || {};
const norm = s => (s || "").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, " ").trim();
const notated = new Map();
for (const [id, w] of Object.entries(W)) {
  const i = w.in || {}; const where = [];
  if ((i.tune || []).length) where.push("tune"); if ((i.score || []).length) where.push("score"); if ((i.analysed || []).length) where.push("analysed");
  if (where.length) notated.set(norm(w.title), where.join("+"));
}
let tuneTitles = new Set();
for (const m of fs.readFileSync(path.join(root, "apps/tunes/tunes-object.js"), "utf8").matchAll(/T:\s*([^\\\n"]+)/g)) tuneTitles.add(norm(m[1]));
// the Concepts list already matched each clip to a works id (apps/shared/works/uses/hutchinson.js), keyed by video + start
(0, eval)(fs.readFileSync(path.join(root, "apps/shared/works/uses/hutchinson.js"), "utf8"));
const clipWork = new Map();
for (const it of window.WORK_USES[0].items) { const v = (it.url.match(/v=([\w-]{11})/) || [])[1], t = (it.url.match(/t=(\d+)/) || [])[1] || "0"; clipWork.set(v + "@" + t, it.work); }
const workAbc = id => { const w = W[id]; if (!w) return ""; const i = w.in || {}; return ["tune", "score", "analysed", "theme"].filter(k => (i[k] || []).length).join("+"); };
const hutchIx = (() => { try { return JSON.parse(fs.readFileSync(path.join(root, "apps/shared/data/hutchinson/index.json"), "utf8")); } catch { return []; } })();
const notation = id => hutchIx.filter(e => e.id === id || e.id === id + "-riff").map(e =>
  e.kind === "score-excerpt" ? "excerpt " + e.abc : e.kind === "chords" && e.abc ? "chords " + e.abc : e.kind === "riff" ? "riff " + e.abc + " (unverified)" : "source " + e.source.id).join("; ");
const hutchBars = id => { const e = hutchIx.find(e => e.id === id && e.bars); return e ? e.bars[0] + (e.bars[1] !== e.bars[0] ? "–" + e.bars[1] : "") : ""; };
let withNotation = 0;
const pages = fs.readdirSync(path.join(root, "theory")).filter(f => f.endsWith(".qmd")).sort();
let out = ["#+TITLE: Hutchinson YouTube excerpts: times, bars, notation", "#+STARTUP: overview",
  "Generated by scripts/works/hutchinson-clips.mjs; edit the Bars and Notes columns by hand only after copying a row out,",
  "or the next run overwrites them. Times are seconds into the video, as the page's embed plays them.", ""];
let n = 0, withBars = 0, withAbc = 0;
for (const f of pages) {
  const src = fs.readFileSync(path.join(root, "theory", f), "utf8");
  const re = /<iframe class="dr-yt" src="[^"]*\/embed\/([\w-]{11})\?([^"]*)" title="([^"]*)"/g;
  const rows = []; let m;
  while ((m = re.exec(src))) {
    const q = new URLSearchParams(m[2]); const start = q.get("start") || "0", end = q.get("end") || "";
    const before = src.slice(0, m.index); const head = (before.match(/^#{2,4} (.+)$/gm) || []).pop() || "";
    const near = src.slice(Math.max(0, m.index - 600), m.index + 600).replace(/<[^>]+>/g, " ");
    const b = near.match(/\b(?:mm?\.|bars?|measures?)\s*(\d+\s*(?:[–-]\s*\d+)?)/i);
    const title = m[3]; const t = norm(title);
    const abc = workAbc(clipWork.get(m[1] + "@" + start)) || notated.get(t) || (tuneTitles.has(t) ? "tune" : "");
    const cid = m[1] + "-" + start, nt = notation(cid), hb = hutchBars(cid); if (nt) withNotation++;
    rows.push(`| ${title.replace(/\|/g, "/")} | ${head.replace(/^#+ /, "").replace(/\{.*\}/, "").trim().replace(/\|/g, "/")} | [[https://youtu.be/${m[1]}?t=${start}][${m[1]}]] | ${start} | ${end} | ${hb || (b ? b[1].replace(/\s/g, "") : "")} | ${abc} | ${nt} |`);
    n++; if (b) withBars++; if (abc) withAbc++;
  }
  if (!rows.length) continue;
  out.push(`* ${f.replace(".qmd", "")} (${rows.length})`, "| Piece | Section | Video | Start | End | Bars | ABC on site | Clip notation |", "|-", ...rows, "");
}
out.splice(4, 0, `${n} clips; ${withBars} with bar numbers found in the page text; ${withAbc} already notated on the site; ${withNotation} with clip notation or a source (apps/shared/data/hutchinson).`, "");
fs.writeFileSync(path.join(root, "research_notes/hutchinson-clips.org"), out.join("\n"));
console.log(`${n} clips, ${withBars} with bars, ${withAbc} with ABC`);
