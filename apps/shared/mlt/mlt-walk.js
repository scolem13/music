  // ---------- saxophone fingerings for a recorder book's notes (books/jri-sax.js) ----------
  // notes: { "G-DO": ["DO", "TI", "SO,"] } recorder keys and syllables (a trailing comma: the octave below). The recorder key
  // is mapped to the class's concert key (JRISax.KEYMAP), then to written pitch for the chosen saxophone.
  var SKEY = "mlt-sax";
  var FROM_DO = { DO: 0, DI: 1, RE: 2, RI: 3, MI: 4, FA: 5, FI: 6, SO: 7, SI: 8, LA: 9, LI: 10, TE: 10, TI: 11 };
  var LETTER = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
  function keyRest(k) {          // "B♭-DO" -> { pc of the resting tone, la: minor }
    var m = /^([A-G])([♭b#♯]?)-(DO|LA)$/.exec(k); if (!m) return null;
    return { pc: (LETTER[m[1]] + (/[♭b]/.test(m[2]) ? -1 : /[#♯]/.test(m[2]) ? 1 : 0) + 12) % 12, la: m[3] === "LA" };
  }
  // a recorder book's note on saxophone: rk "G-DO", syl "TI" (or "SO," an octave down), inst "alto" -> { written, concert, rest }
  // (written midi; null when the recorder key has no concert key yet). The written resting tone sits between E4 and E♭5.
  function saxNote(rk, syl, inst) {
    var C = global.SaxChart, ck = global.JRISax && JRISax.KEYMAP[rk]; if (!C || !ck) return null;
    var tr = C.INSTRUMENTS[inst || "alto"], r = keyRest(ck), restOff = r.la ? 9 : 0;
    var wRest = 64 + (((r.pc - tr - 64) % 12) + 24) % 12, low = /,$/.test(syl), name = syl.replace(/,$/, ""), off = FROM_DO[name] - restOff;
    if (r.la) { if (off < -4) off += 12; } else if (off < 0) off += 12;
    if (!r.la && name === "TI") off = -1;
    var w = wRest + off - (low ? 12 : 0);
    return { written: w, concert: w + tr, rest: wRest, name: name, la: r.la, key: ck };
  }
